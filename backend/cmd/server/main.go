package main
import("context";
"flag";
"fmt";
"log/slog";
"net/http";
"net/mail";
"os";
"os/signal";
"strings";
"syscall";
"time";
"golang.org/x/term";
"sor.hosting/backend/internal/auth";
"sor.hosting/backend/internal/config";
"sor.hosting/backend/internal/database";
"sor.hosting/backend/internal/database/sqlc";
"sor.hosting/backend/internal/httpapi")
func run()error{if len(os.Args)>1&&os.Args[1]=="healthcheck"{client:=http.Client{Timeout:3*time.Second};
res,e:=client.Get("http://127.0.0.1:8080/readyz");
if e!=nil{return e};
defer res.Body.Close();
if res.StatusCode!=200{return fmt.Errorf("not ready")};
return nil};
cfg,e:=config.Load();
if e!=nil{return e};
ctx,cancel:=signal.NotifyContext(context.Background(),os.Interrupt,syscall.SIGTERM);
defer cancel();
db,e:=database.Open(ctx,cfg.Database);
if e!=nil{return e};
defer db.Close();
if e=database.Migrate(ctx,db);
e!=nil{return e};
command:="serve";
if len(os.Args)>1{command=os.Args[1]};
if command=="migrate"{return nil};
if command=="schema-version"{var v int;
e=db.QueryRowContext(ctx,"SELECT COALESCE(MAX(version),0) FROM schema_migrations").Scan(&v);
if e==nil{fmt.Println(v)};
return e};
if command=="backup-db"{flags:=flag.NewFlagSet("backup-db",flag.ContinueOnError);
destination:=flags.String("destination","","SQLite snapshot path");
if e=flags.Parse(os.Args[2:]);
e!=nil{return e};
if *destination==""{return fmt.Errorf("destination required")};
_,e=db.ExecContext(ctx,"VACUUM INTO ?",*destination);
return e};
if command=="create-admin"{flags:=flag.NewFlagSet("create-admin",flag.ContinueOnError);
email:=flags.String("email","","administrator email");
file:=flags.String("password-file","","read password from secret file");
if e=flags.Parse(os.Args[2:]);
e!=nil{return e};
addr,e:=mail.ParseAddress(*email);
if e!=nil||addr.Address!=*email{return fmt.Errorf("invalid email")};
var password []byte;
if *file!=""{password,e=os.ReadFile(*file);
password=[]byte(strings.TrimSuffix(strings.TrimSuffix(string(password),"\n"),"\r"))}else{if !term.IsTerminal(int(os.Stdin.Fd())){return fmt.Errorf("use a terminal or --password-file")};
fmt.Fprint(os.Stderr,"Contraseña del administrador: ");
password,e=term.ReadPassword(int(os.Stdin.Fd()));
fmt.Fprintln(os.Stderr)};
if e!=nil{return e};
defer func(){for i:=range password{password[i]=0}}();
hash,e:=auth.HashPassword(string(password));
if e!=nil{return e};
q:=sqlc.New(db);
if e=q.CreateUser(ctx,sqlc.CreateUserParams{ID:auth.RandomID(),Email:strings.ToLower(*email),PasswordHash:hash,Role:"admin",CreatedAt:time.Now().UTC().Format(time.RFC3339)});
e!=nil{return fmt.Errorf("could not create administrator; check duplicate email")};
fmt.Println("Administrador creado.");
return nil};
if command!="serve"{return fmt.Errorf("command must be serve, migrate or create-admin")};
app:=httpapi.New(db,cfg);
go app.MonitorSites(ctx);
go func(){if e:=app.Jobs.Run(ctx);
e!=nil&&ctx.Err()==nil{slog.Error("job worker stopped");
cancel()}}();
srv:=&http.Server{Addr:cfg.Address,Handler:app.Router(),ReadHeaderTimeout:5*time.Second,ReadTimeout:15*time.Second,IdleTimeout:60*time.Second,MaxHeaderBytes:16<<10};
shutdownDone:=make(chan struct{});
go func(){defer close(shutdownDone);
<-ctx.Done();
shutdown,c:=context.WithTimeout(context.Background(),20*time.Second);
defer c();
if srv.Shutdown(shutdown)!=nil{_ = srv.Close()}}();
slog.Info("SOR Hosting listening","address",cfg.Address);
e=srv.ListenAndServe();
if e==http.ErrServerClosed{<-shutdownDone;
return nil};
cancel();
<-shutdownDone;
return e}
func main(){if e:=run();
e!=nil{slog.Error("SOR Hosting stopped","error",e.Error());
os.Exit(1)}}
